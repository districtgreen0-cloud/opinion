// Cards feature: map shortcut → Market › Cards, country switch, filters, details. Needs `npx vite preview --port 4701`.
import { chromium, webkit, devices } from 'playwright-core'
const OUT = new URL('./shots/', import.meta.url).pathname
const R = {}, errs = []
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 })).newPage()
p.on('pageerror', (e) => errs.push(e.message))
await p.goto('http://localhost:4701'); await p.waitForFunction(() => window.__map?.loaded(), null, { timeout: 120000 }); await p.waitForTimeout(5000)
const sc = p.getByRole('button', { name: 'Crypto cards available here' })
R.shortcut = (await sc.innerText()).trim()
await sc.click(); await p.waitForTimeout(900)
const panel = p.locator('section').first()
const head = await panel.innerText()
R.header = head.slice(head.indexOf('CARDS IN'), head.indexOf('CARDS IN') + 40).replace(/\n/g, ' ')
R.ukRows = await panel.locator('ul > li:has(a:has-text("Apply on"))').count()
R.cardArt = await panel.locator('[role=img][aria-label$="card illustration"]').count()
await p.screenshot({ path: OUT + 'cards-uk.png' })
await panel.getByRole('button', { name: '◎ Solana' }).click(); await p.waitForTimeout(300)
R.ukSolana = await panel.locator('ul').first().locator('> li').count()
await panel.getByRole('button', { name: '◎ Solana' }).click()
await panel.getByRole('button', { name: 'Fees & details' }).first().click(); await p.waitForTimeout(200)
R.details = (await panel.innerText()).includes('Fees:')
await panel.getByRole('button', { name: 'United States' }).click(); await p.waitForTimeout(300)
R.us = (await panel.innerText()).match(/United States · (\d+)/)?.[1]
await panel.getByRole('button', { name: 'Serbia' }).click(); await p.waitForTimeout(300)
const rs = await panel.innerText()
R.rs = rs.match(/Serbia · (\d+)/)?.[1]; R.rsEmptyMsg = rs.includes('No confirmed cards'); R.rsOthers = /\d+ not available or unconfirmed in Serbia/.test(rs)
R.noTodey = !(await p.content()).toLowerCase().includes('todey')
console.log(JSON.stringify({ R, errs }, null, 1))
await b.close()
const w = await webkit.launch()
const m = await (await w.newContext({ ...devices['iPhone 15'] })).newPage()
m.on('pageerror', (e) => errs.push('iphone ' + e.message))
await m.goto('http://localhost:4701'); await m.waitForFunction(() => window.__map?.loaded(), null, { timeout: 120000 }); await m.waitForTimeout(5000)
await m.getByRole('button', { name: 'Crypto cards available here' }).click(); await m.waitForTimeout(900)
const ov = await m.evaluate(() => document.documentElement.scrollWidth <= innerWidth)
await m.screenshot({ path: OUT + 'cards-iphone.png' })
console.log('iphone noHScroll', ov, 'errs', JSON.stringify(errs))
await w.close()
