// San Francisco: city switch, live events, CA cards, traffic lights, hex posting, iPhone. Usage: node e2e/sf.mjs [url]
import { chromium, webkit, devices } from 'playwright-core'
const URL_ = process.argv[2] ?? 'https://opinion-london.calderabalkan.workers.dev'
const OUT = new URL('./shots/', import.meta.url).pathname
const R = {}, errs = []
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 })).newPage()
p.on('pageerror', (e) => errs.push(e.message))
await p.goto(URL_); await p.waitForFunction(() => window.__map?.loaded(), null, { timeout: 120000 }); await p.waitForTimeout(3000)
// switch city via the top-bar menu
await p.getByRole('button', { name: /London/ }).first().click(); await p.waitForTimeout(400)
await p.getByRole('button', { name: /San Francisco/ }).click()
await p.waitForTimeout(9000)
R.center = await p.evaluate(() => { const c = window.__map.getCenter(); return [+c.lng.toFixed(3), +c.lat.toFixed(3)] })
const tabs = p.getByRole('tablist', { name: 'Show on map' })
R.tabs = (await tabs.innerText()).replace(/\n/g, ' ')
await tabs.getByRole('tab', { name: /^Events/i }).click(); await p.waitForTimeout(800)
R.events = await p.locator('aside li').count(); R.luma = await p.locator('aside li', { hasText: 'LUMA' }).count()
R.firstEvent = (await p.locator('aside li').first().innerText()).replace(/\n/g, ' | ').slice(0, 90)
await p.screenshot({ path: OUT + 'sf-events.png' })
await tabs.getByRole('tab', { name: /^All/i }).click()
// cards → California
const sc = p.getByRole('button', { name: 'Crypto cards available here' })
R.cardsButton = (await sc.innerText()).trim()
await sc.click({ timeout: 90000 }); await p.waitForTimeout(800)
const panel = p.locator('section').first()
const t = await panel.innerText()
R.cardsHeader = t.match(/California, US · (\d+)/)?.[1]
R.caHasKrak = t.includes('Krak'); R.caHasPhantom = t.includes('Phantom')
await p.screenshot({ path: OUT + 'sf-cards.png' })
await panel.getByRole('button', { name: 'Close' }).click()
// traffic lights + a hex post (teleport)
await p.evaluate(() => window.__map.jumpTo({ center: [-122.4035, 37.7855], zoom: 17, pitch: 58, bearing: 28 })); await p.waitForTimeout(6000)
await p.screenshot({ path: OUT + 'sf-lights.png' })
const [x, y] = await p.evaluate(() => { const q = window.__map.project([-122.4035, 37.7855]); return [q.x, q.y] })
await p.mouse.click(x, y); await p.waitForTimeout(800)
await p.getByRole('button', { name: /Teleport here/ }).click(); await p.waitForTimeout(300)
await p.locator('section').first().getByRole('tab', { name: /^Notes/ }).click()
await p.getByLabel('Comment').fill('hello from SoMa'); await p.getByRole('button', { name: 'Drop', exact: true }).click(); await p.waitForTimeout(600)
R.hexPost = (await p.locator('section').first().innerText()).includes('hello from SoMa')
R.res10 = (await p.locator('section').first().innerText()).includes('RES 10')
console.log(JSON.stringify({ R, errs }, null, 1))
await b.close()
const w = await webkit.launch()
const m = await (await w.newContext({ ...devices['iPhone 15'] })).newPage()
m.on('pageerror', (e) => errs.push('iphone ' + e.message))
await m.addInitScript(() => localStorage.setItem('opinion:city2', JSON.stringify('sf')))
await m.goto(URL_); await m.waitForFunction(() => window.__map?.loaded(), null, { timeout: 120000 }); await m.waitForTimeout(6000)
await m.screenshot({ path: OUT + 'sf-iphone.png' })
console.log('iphone city', await m.locator('text=San Francisco').count(), 'errs', JSON.stringify(errs))
await w.close()
