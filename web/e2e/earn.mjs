// Earn mode: opt-in consent per tier → contributions + points → My data (export / delete / stop). Usage: node e2e/earn.mjs [url]
import { chromium, webkit, devices } from 'playwright-core'
const URL_ = process.argv[2] ?? 'http://localhost:4701'
const OUT = new URL('./shots/', import.meta.url).pathname
const errs = [], R = {}
const init = () => { sessionStorage.setItem('opinion:splash', '1'); sessionStorage.setItem('opinion:entered', '1'); localStorage.setItem('opinion:busyAt', String(Date.now() - 15 * 60000 + 21000)) }
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2, geolocation: { latitude: 51.5108, longitude: -0.1172 }, permissions: ['geolocation'], acceptDownloads: true })
const p = await ctx.newPage()
p.on('pageerror', (e) => errs.push(e.message))
await p.addInitScript(init)
await p.goto(URL_); await p.waitForFunction(() => window.__map?.loaded(), null, { timeout: 120000 }); await p.waitForTimeout(3000)
R.btn = (await p.getByRole('button', { name: /^Earn/ }).innerText()).trim()
await p.getByRole('button', { name: /^Earn/ }).click(); await p.waitForTimeout(700)
const dlg = p.getByRole('dialog', { name: 'Earn mode' })
R.startDisabled = await dlg.getByRole('button', { name: 'Start earning' }).isDisabled()
await p.screenshot({ path: OUT + 'earn-consent.png' })
await dlg.getByRole('switch', { name: 'Share Interests' }).click()
await dlg.getByRole('checkbox').check()
await dlg.getByRole('button', { name: 'Start earning' }).click(); await p.waitForTimeout(800)
R.consent = await p.evaluate(() => JSON.parse(localStorage.getItem('opinion:earnConsent')))
await p.getByRole('button', { name: 'Close' }).first().click()
// location → presence ping; open Sports → interest
await p.getByRole('button', { name: /Centre/ }).click().catch(() => {}); await p.waitForTimeout(2500)
await p.getByRole('tab', { name: /^Sports/i }).click(); await p.waitForTimeout(800)
await p.getByRole('dialog', { name: 'Quick question' }).waitFor({ timeout: 40000 }).catch(() => {})
R.prompt = await p.getByRole('dialog', { name: 'Quick question' }).count()
await p.screenshot({ path: OUT + 'earn-prompt.png' })
if (R.prompt) { await p.getByRole('button', { name: 'Busy 4 of 5' }).click(); await p.waitForTimeout(500) }
R.log = await p.evaluate(() => JSON.parse(localStorage.getItem('opinion:earnLog')).map((e) => [e.tier, e.kind, e.cell ? e.cell.length + 'ch res' : '', e.value ?? '']))
R.resCheck = await p.evaluate(() => JSON.parse(localStorage.getItem('opinion:earnLog')).filter((e) => e.cell).every((e) => e.cell.startsWith('88')))
R.btnOn = (await p.getByRole('button', { name: /Earning|Earn/ }).first().innerText()).trim()
await p.getByRole('button', { name: /Earning/ }).click(); await p.waitForTimeout(700)
await p.screenshot({ path: OUT + 'earn-mydata.png' })
const [dl] = await Promise.all([p.waitForEvent('download'), dlg.getByRole('button', { name: '⤓ Export' }).click()])
R.exportName = dl.suggestedFilename()
await dlg.getByRole('button', { name: 'Delete my data' }).click()
await dlg.getByRole('button', { name: 'Yes, delete everything' }).click(); await p.waitForTimeout(600)
R.afterDelete = await p.evaluate(() => [localStorage.getItem('opinion:earnLog'), localStorage.getItem('opinion:earnConsent')])
console.log(JSON.stringify({ R, errs }, null, 1))
await b.close()
const w = await webkit.launch()
const m = await (await w.newContext({ ...devices['iPhone 15'] })).newPage()
m.on('pageerror', (e) => errs.push('iphone ' + e.message))
await m.addInitScript(init)
await m.goto(URL_); await m.waitForFunction(() => window.__map?.loaded(), null, { timeout: 120000 }); await m.waitForTimeout(3000)
const bar = await m.evaluate(() => { const els = [...document.querySelectorAll('button')].filter((b) => b.getBoundingClientRect().top < 60); return els.map((b) => Math.round(b.getBoundingClientRect().right)).sort((a, z) => z - a)[0] })
await m.getByRole('button', { name: /^Earn/ }).click(); await m.waitForTimeout(800)
await m.screenshot({ path: OUT + 'earn-iphone.png' })
console.log('iphone rightmost top button', bar, '/ 393', 'errs', JSON.stringify(errs))
await w.close()
