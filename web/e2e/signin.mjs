// Sign in / Sign up: one button → wallet, Google or email. Usage: node e2e/signin.mjs [url]
import { chromium, webkit, devices } from 'playwright-core'
const URL_ = process.argv[2] ?? 'http://localhost:4701'
const OUT = new URL('./shots/', import.meta.url).pathname
const errs = [], R = {}
const init = () => { sessionStorage.setItem('opinion:splash', '1'); sessionStorage.setItem('opinion:entered', '1') }
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 })).newPage()
p.on('pageerror', (e) => errs.push(e.message))
await p.addInitScript(init)
await p.goto(URL_); await p.waitForFunction(() => window.__map?.loaded(), null, { timeout: 120000 }); await p.waitForTimeout(3000)
const btn = p.getByRole('button', { name: 'Sign in or sign up' })
R.button = (await btn.innerText()).trim()
R.oldConnect = await p.getByRole('button', { name: /^Connect$/ }).count()
await btn.click(); await p.waitForTimeout(800)
const dlg = p.getByRole('dialog', { name: /Sign in or sign up/ })
R.options = await dlg.locator('button').allInnerTexts().then((a) => a.map((t) => t.trim()).filter(Boolean).slice(0, 8))
await p.screenshot({ path: OUT + 'signin-in.png' })
await dlg.getByRole('tab', { name: 'Sign up' }).click(); await p.waitForTimeout(300)
R.upTitle = await dlg.locator('h2').innerText()
R.upGoogle = await dlg.getByRole('button', { name: /Sign up with Google/ }).count()
await p.screenshot({ path: OUT + 'signin-up.png' })
await dlg.getByRole('button', { name: /Connect wallet/ }).click(); await p.waitForTimeout(500)
R.walletStep = await dlg.locator('h2').innerText()
await p.screenshot({ path: OUT + 'signin-wallet.png' })
await dlg.getByRole('button', { name: 'Use a demo wallet' }).click(); await p.waitForTimeout(800)
R.closed = await dlg.count()
R.walletPill = (await p.getByRole('button', { name: /Disconnect|…/ }).first().innerText().catch(() => '')).replace(/\n/g, ' ')
R.authBtnGone = await p.getByRole('button', { name: 'Sign in or sign up' }).count()
console.log(JSON.stringify({ R, errs }, null, 1))
await b.close()
const w = await webkit.launch()
const m = await (await w.newContext({ ...devices['iPhone 15'] })).newPage()
m.on('pageerror', (e) => errs.push('iphone ' + e.message))
await m.addInitScript(init)
await m.goto(URL_); await m.waitForFunction(() => window.__map?.loaded(), null, { timeout: 120000 }); await m.waitForTimeout(4000)
await m.getByRole('button', { name: 'Sign in or sign up' }).click(); await m.waitForTimeout(900)
await m.screenshot({ path: OUT + 'signin-iphone.png' })
console.log('iphone ok, errs', JSON.stringify(errs))
await w.close()
