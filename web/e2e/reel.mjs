// Slot-machine city picker: reel shows one city, spin lands elsewhere, drag/arrows step, Fly in enters. Usage: node e2e/reel.mjs [url]
import { chromium, webkit, devices } from 'playwright-core'
const URL_ = process.argv[2] ?? 'http://localhost:4701'
const OUT = new URL('./shots/', import.meta.url).pathname
const errs = [], R = {}
const sel = (p) => p.locator('[role=option][aria-selected=true]').first().innerText()
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 })).newPage()
p.on('pageerror', (e) => errs.push(e.message))
await p.goto(URL_)
const dlg = p.getByRole('dialog', { name: 'Choose your city' })
await dlg.waitFor({ timeout: 90000 }); await p.waitForTimeout(2600)
R.box = await dlg.boundingBox()
R.start = await sel(p)
await p.screenshot({ path: OUT + 'reel-1.png' })
await p.getByRole('button', { name: 'Next city' }).click(); await p.waitForTimeout(700); R.afterNext = await sel(p)
await p.getByRole('button', { name: 'Pull the lever to spin' }).click(); await p.waitForTimeout(900)
await p.screenshot({ path: OUT + 'reel-2-spinning.png' })
await p.waitForTimeout(2600); R.afterSpin = await sel(p)
await p.waitForTimeout(1600)
R.globeCenter = await p.evaluate(() => { const c = window.__map.getCenter(); return [+c.lng.toFixed(1), +c.lat.toFixed(1)] })
await p.screenshot({ path: OUT + 'reel-3-landed.png' })
// drag down one face
const win = await p.locator('.cp-win').boundingBox()
await p.mouse.move(win.x + win.width / 2, win.y + win.height / 2); await p.mouse.down(); await p.mouse.move(win.x + win.width / 2, win.y + win.height / 2 + 46, { steps: 8 }); await p.waitForTimeout(250); await p.mouse.up(); await p.waitForTimeout(900)
R.afterDrag = await sel(p)
const target = R.afterDrag
await p.getByRole('button', { name: 'Fly in →' }).click(); await p.waitForTimeout(12000)
R.entered = (await p.getByRole('button', { name: new RegExp(target) }).first().innerText()).trim()
R.zoom = await p.evaluate(() => +window.__map.getZoom().toFixed(1))
console.log(JSON.stringify({ R, errs }, null, 1))
await b.close()
const w = await webkit.launch()
const m = await (await w.newContext({ ...devices['iPhone 15'] })).newPage()
m.on('pageerror', (e) => errs.push('iphone ' + e.message))
await m.goto(URL_)
await m.getByRole('dialog', { name: 'Choose your city' }).waitFor({ timeout: 90000 }); await m.waitForTimeout(2800)
await m.screenshot({ path: OUT + 'reel-iphone.png' })
console.log('iphone box', JSON.stringify(await m.getByRole('dialog', { name: 'Choose your city' }).boundingBox()), 'errs', JSON.stringify(errs))
await w.close()
